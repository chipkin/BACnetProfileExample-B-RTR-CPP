// BACnet Profile Example - B-RTR (BACnet Router) - C++
//
// This example implements the BACnet "B-RTR" (Router) device profile with the
// CAS BACnet Stack. It is the B-ASC (Application Specific Controller) example
// minus DeviceCommunicationControl, plus TWO Network Port objects and physical
// inter-datalink routing between them (ANSI/ASHRAE 135 cl. 6.6, Annex L NM-RC-B).
//
// A B-RTR is a stand-alone BACnet router: a device that forwards NPDUs between
// two (or more) directly-connected BACnet networks and answers the network-layer
// messages that let other devices discover and use it as a router:
//
//     DS-RP-B    - respond to ReadProperty requests,
//     DS-WP-B    - allow other devices to WriteProperty its objects,
//     DM-DDB-A   - INITIATE Who-Is (SendWhoIs) as well as answer it - a router is
//                  expected to actively discover devices on the networks it joins,
//                  not just wait to be asked,
//     DM-DOB-B   - answer Who-Has,
//     NM-RC-B    - Network Management - Router Configuration: configure router
//                  ports/routes, answer Who-Is-Router-To-Network with
//                  I-Am-Router-To-Network, and announce Network-Number-Is.
//
// plus discovery (Who-Is/I-Am, Who-Has/I-Have). This example does NOT implement
// DM-LM-B (AddListElement/RemoveListElement, services 8/9): see TODO.md - the
// customer-facing STATIC build of the pinned stack does not compile that support
// in, so it is a documented gap rather than a faked claim.
//
// The device keeps the same base objects as B-ASC/B-SA - three read-only sensor
// inputs and three commandable outputs a client drives with WriteProperty - PLUS
// a SECOND Network Port object, one per side of the router:
//
//     Device 389018            "Rainbow"      (instance configurable with --deviceID)
//     Analog Input  1          "Bronze"       (REAL, degrees Celsius; read-only)
//     Binary Input  1          "Emerald"      (active / inactive; read-only)
//     Multi-State Input 1      "Hot Pink"     (state 1..3; read-only)
//     Analog Output 1          "Chartreuse"   (REAL setpoint; WRITABLE, commandable)
//     Binary Output 1          "Fuchsia"      (active / inactive; WRITABLE, commandable)
//     Multi-State Output 1     "Indigo"       (state 1..3; WRITABLE, commandable)
//     Network Port 1           "Vermilion"    (BACnet/IP port A - network 1)
//     Network Port 2           "Vermilion 2"  (BACnet/IP port B - network 2)
//
// F-MULTIPORT: the two Network Ports each own their own UDP socket, via the
// common/ 2.3.0+ multi-port SetupUDP(port, networkPortInstance) /
// SendIAm(deviceInstance, networkPortInstance) overloads - see
// common/CASExampleHelper.h/.cpp for how the shared transport callbacks
// dispatch on networkPortInstance. This is the FIRST example in the series to
// use more than one Network Port; everything below is written to be a clear
// pattern for a later multi-port example (e.g. B-GW) to copy.
//
// F-ROUTER: BACnetStack_AddRouterPort registers each Network Port's directly
// connected network with the stack's router logic; BACnetStack_SetRouterEnabled
// turns forwarding on. A third, ONE-HOP-AWAY network is configured with
// BACnetStack_AddRouterRoute purely to demonstrate that API - see the
// DEMO_REMOTE_NETWORK comment below for what is and is not verified about it.
//
// Output objects are COMMANDABLE: their Present_Value is driven by a 16-slot
// BACnet Priority_Array, exactly as in B-SA/B-ASC. See GetCommandable() etc.
// below - this part is unchanged from B-ASC.
//
// To be a conformant BACnet device (Protocol_Revision 24) each object must
// expose its full set of REQUIRED properties. Most are generated by the stack
// (Object_Identifier, Object_Type, Status_Flags, Object_List, Protocol_*). A
// Network Port additionally gets Network_Number, Network_Number_Quality,
// BACnet_IP_Mode and MAC_Address from the stack once AddNetworkPortObject is
// called with the right arguments - see the callbacks below for the handful
// this application still has to supply (IP_Address, IP_Subnet_Mask, ...).
//
// Interactive keys (handled by the shared helper): h = help, q = quit,
// up/down = nudge Analog Input 1 by +/-1.1, r = re-send I-Am-Router-To-Network
// on both ports now (common/ 2.4.0+). Command line: --port <n> (Network Port 1 /
// Vermilion), --port2 <n> (Network Port 2 / Vermilion 2, default --port + 1),
// --deviceID <n>.
//
// All the UDP/stack plumbing lives in common/CASExampleHelper so this file can
// stay focused on the BACnet logic.
// =============================================================================

