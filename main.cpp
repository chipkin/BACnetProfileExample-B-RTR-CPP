bool SetPropertyReal(const uint32_t deviceInstance, const uint16_t objectType,
                     const uint32_t objectInstance, const uint32_t propertyIdentifier,
                     const float value, const bool useArrayIndex,
                     const uint32_t propertyArrayIndex, const uint8_t priority,
                     uint32_t* errorCode) {
    (void)useArrayIndex;
    (void)propertyArrayIndex;
    (void)errorCode;
    if (deviceInstance != g_deviceInstance) {
        return false;
    }
    Commandable* c = GetCommandable(objectType, objectInstance);
    if (c != NULL && objectType == OBJECT_TYPE_ANALOG_OUTPUT &&
        propertyIdentifier == PROPERTY_IDENTIFIER_PRESENT_VALUE) {
        CommandWrite(c, priority, (double)value);
        printf("WriteProperty: Analog Output %u (Chartreuse) <- %.2f @ priority %u\n",
               objectInstance, value, EffectivePriority(priority));
        return true;
    }
    return false;
}

bool SetPropertyEnumerated(const uint32_t deviceInstance, const uint16_t objectType,
                           const uint32_t objectInstance, const uint32_t propertyIdentifier,
                           const uint32_t value, const bool useArrayIndex,
                           const uint32_t propertyArrayIndex, const uint8_t priority,
                           uint32_t* errorCode) {
    (void)useArrayIndex;
    (void)propertyArrayIndex;
    if (deviceInstance != g_deviceInstance) {
        return false;
    }
    Commandable* c = GetCommandable(objectType, objectInstance);
    if (c != NULL && objectType == OBJECT_TYPE_BINARY_OUTPUT &&
        propertyIdentifier == PROPERTY_IDENTIFIER_PRESENT_VALUE) {
        if (value > 1) {
            *errorCode = ERROR_CODE_VALUE_OUT_OF_RANGE;
            return false;
        }
        CommandWrite(c, priority, (double)value);
        printf("WriteProperty: Binary Output %u (Fuchsia) <- %s @ priority %u\n",
               objectInstance, value ? "active" : "inactive", EffectivePriority(priority));
        return true;
    }
    return false;
}

bool SetPropertyUnsignedInteger(const uint32_t deviceInstance, const uint16_t objectType,
                                const uint32_t objectInstance, const uint32_t propertyIdentifier,
                                const uint32_t value, const bool useArrayIndex,
                                const uint32_t propertyArrayIndex, const uint8_t priority,
                                uint32_t* errorCode) {
    (void)useArrayIndex;
    (void)propertyArrayIndex;
    if (deviceInstance != g_deviceInstance) {
        return false;
    }
    Commandable* c = GetCommandable(objectType, objectInstance);
    if (c != NULL && objectType == OBJECT_TYPE_MULTI_STATE_OUTPUT &&
        propertyIdentifier == PROPERTY_IDENTIFIER_PRESENT_VALUE) {
        if (value < 1 || value > MULTI_STATE_OUTPUT_NUMBER_OF_STATES) {
            *errorCode = ERROR_CODE_VALUE_OUT_OF_RANGE;
            return false;
        }
        CommandWrite(c, priority, (double)value);
        printf("WriteProperty: Multi-State Output %u (Indigo) <- state %u @ priority %u\n",
               objectInstance, value, EffectivePriority(priority));
        return true;
    }
    return false;
}

bool SetPropertyNull(const uint32_t deviceInstance, const uint16_t objectType,
                     const uint32_t objectInstance, const uint32_t propertyIdentifier,
                     const bool useArrayIndex, const uint32_t propertyArrayIndex,
                     const uint8_t priority, uint32_t* errorCode) {
    (void)useArrayIndex;
    (void)propertyArrayIndex;
    (void)errorCode;
    if (deviceInstance != g_deviceInstance) {
        return false;
    }
    Commandable* c = GetCommandable(objectType, objectInstance);
    if (c != NULL && propertyIdentifier == PROPERTY_IDENTIFIER_PRESENT_VALUE) {
        CommandRelinquish(c, priority);
        printf("WriteProperty: relinquished %s %u @ priority %u\n",
               objectType == OBJECT_TYPE_ANALOG_OUTPUT ? "Analog Output" :
               objectType == OBJECT_TYPE_BINARY_OUTPUT ? "Binary Output" :
               "Multi-State Output",
               objectInstance, EffectivePriority(priority));
        return true;
    }
    return false;
}

// -----------------------------------------------------------------------------
// 2c. Router helpers (F-ROUTER)
//
// SendIAmRouterToNetwork/SendWhoIsRouterToNetwork/SendNetworkNumberIs all take
// a DESTINATION connection string (who to send TO), not a source. Broadcasting
// on one of our own ports means "the local subnet broadcast of THAT port's
// network" - the same address CASExampleHelper::SendIAm computes internally,
// rebuilt here because main.cpp does not have access to that private helper.
// -----------------------------------------------------------------------------
static void BuildLocalBroadcastConnectionString(uint16_t port, uint8_t connectionString[6]) {
    uint8_t bcast[4] = { 255, 255, 255, 255 };
    uint8_t ip[4], mask[4];
    if (CASExampleHelper::GetLocalIPv4(ip, mask)) {
        bcast[0] = (uint8_t)(ip[0] | ~mask[0]);
        bcast[1] = (uint8_t)(ip[1] | ~mask[1]);
        bcast[2] = (uint8_t)(ip[2] | ~mask[2]);
        bcast[3] = (uint8_t)(ip[3] | ~mask[3]);
    }
    connectionString[0] = bcast[0];
    connectionString[1] = bcast[1];
    connectionString[2] = bcast[2];
    connectionString[3] = bcast[3];
    connectionString[4] = (uint8_t)((port >> 8) & 0xFF);
    connectionString[5] = (uint8_t)(port & 0xFF);
}

// Broadcast I-Am-Router-To-Network on BOTH ports, each announcing this
// router's FULL configured routing table (networkNumbers = NULL, count = 0 -
// see BACnetStack_SendIAmRouterToNetwork's doc comment: since CAS BACnet Stack
// #1014 this works for a physical router too, and reports every enabled
// port's directly-connected network plus every BACnetStack_AddRouterRoute
// entry). Called once at start-up and again whenever the 'r' key is pressed.
static void AnnounceRouterToBothNetworks() {
    uint8_t cs1[6];
    BuildLocalBroadcastConnectionString(g_bacnetIpUdpPort1, cs1);
    const bool ok1 = BACnetStack_SendIAmRouterToNetwork(
        NULL, 0, cs1, 6, NETWORK_PORT_1_INSTANCE, true, 0, NULL, 0);

    uint8_t cs2[6];
    BuildLocalBroadcastConnectionString(g_bacnetIpUdpPort2, cs2);
    const bool ok2 = BACnetStack_SendIAmRouterToNetwork(
        NULL, 0, cs2, 6, NETWORK_PORT_2_INSTANCE, true, 0, NULL, 0);

    printf("FYI: I-Am-Router-To-Network broadcast on Network Port 1 (Vermilion): %s; "
           "on Network Port 2 (Vermilion 2): %s\n",
           ok1 ? "sent" : "FAILED", ok2 ? "sent" : "FAILED");
}

// -----------------------------------------------------------------------------
// 3. main()
// -----------------------------------------------------------------------------
int main(int argc, char** argv) {
    setvbuf(stdout, NULL, _IONBF, 0);

    if (!LoadBACnetFunctions()) {
        fprintf(stderr, "Error: failed to load the CAS BACnet Stack: %s\n",
                CASBACnetStackAdapter_LastError());
        return 1;
    }

    if (CASExampleHelper::HandleHelpAndVersionArgs(argc, argv, APP_NAME, APP_VERSION)) {
        return 0;
    }
    // --port sets Network Port 1 (Vermilion); --port2 sets Network Port 2
    // (Vermilion 2), defaulting to --port + 1 so the example runs out of the
    // box with two DIFFERENT UDP ports and no extra flags. ParsePortArg (the
    // shared helper) only knows the one "--port" flag, so --port2 is parsed
    // locally with the same validation rule.
    const uint16_t port1 = CASExampleHelper::ParsePortArg(argc, argv, 47808);
    uint16_t port2 = (uint16_t)(port1 + 1);
    for (int i = 1; i + 1 < argc; ++i) {
        if (strcmp(argv[i], "--port2") == 0) {
            char* end = NULL;
            errno = 0;
            const long p = strtol(argv[i + 1], &end, 10);
            if (errno == 0 && end != argv[i + 1] && *end == '\0' && p > 0 && p <= 65535) {
                port2 = (uint16_t)p;
            } else {
                printf("Warning: ignoring invalid --port2 \"%s\" (want 1..65535); using %u.\n",
                       argv[i + 1], (unsigned)port2);
            }
        }
    }
    if (port2 == port1) {
        fprintf(stderr, "Error: --port2 (%u) must differ from --port (%u) - they are two "
                        "separate BACnet/IP networks on this router.\n",
                (unsigned)port2, (unsigned)port1);
        return 1;
    }
    g_deviceInstance = CASExampleHelper::ParseDeviceIdArg(argc, argv, g_deviceInstance);
    CASExampleHelper::PrintVersion(APP_NAME, APP_VERSION);

    // --- Bind BOTH BACnet/IP sockets (F-MULTIPORT) --------------------------
    // SetNetworkPortInstance first, so the single-argument SetupUDP(port1) and
    // (later) SendIAm(deviceInstance) act on Network Port 1 by default; port 2
    // is bound with the explicit two-argument overload.
    CASExampleHelper::SetNetworkPortInstance(NETWORK_PORT_1_INSTANCE);
    if (!CASExampleHelper::SetupUDP(port1)) {
        return 1;
    }
    if (!CASExampleHelper::SetupUDP(port2, NETWORK_PORT_2_INSTANCE)) {
        return 1;
    }
    g_bacnetIpUdpPort1 = port1;
    g_bacnetIpUdpPort2 = port2;
    if (!CASExampleHelper::GetLocalIPv4(g_ipAddress, g_ipSubnetMask)) {
        printf("FYI: could not read a local IPv4 address; both Network Ports will report "
               "IP_Address 0.0.0.0.\n");
    }

    // --- Register callbacks -------------------------------------------------
    // One set of transport/time callbacks serves BOTH ports - common/ 2.3.0+
    // dispatches on networkPortInstance internally (see CASExampleHelper.cpp).
    CASExampleHelper::RegisterCommonCallbacks();
    BACnetStack_RegisterCallbackGetPropertyReal(GetPropertyReal);
    BACnetStack_RegisterCallbackGetPropertyEnumerated(GetPropertyEnumerated);
    BACnetStack_RegisterCallbackGetPropertyUnsignedInteger(GetPropertyUnsignedInteger);
    BACnetStack_RegisterCallbackGetPropertyCharacterString(GetPropertyCharString);
    BACnetStack_RegisterCallbackGetPropertyBool(GetPropertyBool);
    BACnetStack_RegisterCallbackGetPropertyOctetString(GetPropertyOctetString);
    BACnetStack_RegisterCallbackSetPropertyReal(SetPropertyReal);
    BACnetStack_RegisterCallbackSetPropertyEnumerated(SetPropertyEnumerated);
    BACnetStack_RegisterCallbackSetPropertyUnsignedInteger(SetPropertyUnsignedInteger);
    BACnetStack_RegisterCallbackSetPropertyNull(SetPropertyNull);
    // NOTE: no DeviceCommunicationControl callback - this profile (unlike
    // B-ASC, its seed) does not include DM-DCC-B.

    // --- Create the device --------------------------------------------------
    if (!BACnetStack_AddDevice(g_deviceInstance)) {
        printf("Error: Failed to add the Device %u.\n", g_deviceInstance);
        return 1;
    }

    // DS-RP-B, DS-WP-B: ReadProperty, WriteProperty.
    if (!BACnetStack_SetServiceEnabled(g_deviceInstance, SERVICE_READ_PROPERTY, true)) {
        printf("Error: Failed to enable the ReadProperty service.\n");
        return 1;
    }
    if (!BACnetStack_SetServiceEnabled(g_deviceInstance, SERVICE_WRITE_PROPERTY, true)) {
        printf("Error: Failed to enable the WriteProperty service.\n");
        return 1;
    }
    // DM-DDB-A/B, DM-DOB-B: Who-Is/I-Am (both directions - DM-DDB-A means this
    // device also INITIATES Who-Is, not just answers it) and Who-Has/I-Have.
    // NM-RC-B's network-layer messages (Who-Is-Router-To-Network,
    // I-Am-Router-To-Network, Network-Number-Is) are NOT gated by
    // SetServiceEnabled - they are enabled purely by BACnetStack_AddRouterPort
    // + BACnetStack_SetRouterEnabled below.
    if (!BACnetStack_SetServiceEnabled(g_deviceInstance, SERVICE_WHO_IS, true) ||
        !BACnetStack_SetServiceEnabled(g_deviceInstance, SERVICE_I_AM, true) ||
        !BACnetStack_SetServiceEnabled(g_deviceInstance, SERVICE_WHO_HAS, true) ||
        !BACnetStack_SetServiceEnabled(g_deviceInstance, SERVICE_I_HAVE, true)) {
        printf("Error: Failed to enable the discovery services (Who-Is/I-Am, Who-Has/I-Have).\n");
        return 1;
    }

    // --- Add the read-only sensor objects -----------------------------------
    if (!BACnetStack_AddObject(g_deviceInstance, OBJECT_TYPE_ANALOG_INPUT, ANALOG_INPUT_INSTANCE)) {
        printf("Error: Failed to add Analog Input %u (Bronze).\n", ANALOG_INPUT_INSTANCE);
        return 1;
    }
    if (!BACnetStack_AddObject(g_deviceInstance, OBJECT_TYPE_BINARY_INPUT, BINARY_INPUT_INSTANCE)) {
        printf("Error: Failed to add Binary Input %u (Emerald).\n", BINARY_INPUT_INSTANCE);
        return 1;
    }
    if (!BACnetStack_AddObject(g_deviceInstance, OBJECT_TYPE_MULTI_STATE_INPUT, MULTI_STATE_INPUT_INSTANCE)) {
        printf("Error: Failed to add Multi-State Input %u (Hot Pink).\n", MULTI_STATE_INPUT_INSTANCE);
        return 1;
    }

    // --- Add the commandable OUTPUT objects ----------------------------------
    if (!BACnetStack_AddObject(g_deviceInstance, OBJECT_TYPE_ANALOG_OUTPUT, ANALOG_OUTPUT_INSTANCE)) {
        printf("Error: Failed to add Analog Output %u (Chartreuse).\n", ANALOG_OUTPUT_INSTANCE);
        return 1;
    }
    if (!BACnetStack_AddObject(g_deviceInstance, OBJECT_TYPE_BINARY_OUTPUT, BINARY_OUTPUT_INSTANCE)) {
        printf("Error: Failed to add Binary Output %u (Fuchsia).\n", BINARY_OUTPUT_INSTANCE);
        return 1;
    }
    if (!BACnetStack_AddObject(g_deviceInstance, OBJECT_TYPE_MULTI_STATE_OUTPUT, MULTI_STATE_OUTPUT_INSTANCE)) {
        printf("Error: Failed to add Multi-State Output %u (Indigo).\n", MULTI_STATE_OUTPUT_INSTANCE);
        return 1;
    }

    // --- Add BOTH Network Port objects (F-MULTIPORT) -------------------------
    // Each one is BACNET_APPLICATION level, so it gets a Network_Number and
    // Network_Number_Quality; we pass CONFIGURED, since a router locally
    // configures the number of each network it joins rather than learning it.
    if (!BACnetStack_AddNetworkPortObject(
            g_deviceInstance, NETWORK_PORT_1_INSTANCE,
            NETWORK_PORT_NETWORK_TYPE_IPV4,
            NETWORK_PORT_PROTOCOL_LEVEL_BACNET_APPLICATION,
            NETWORK_NUMBER_PORT_1,
            NETWORK_NUMBER_QUALITY_CONFIGURED,
            NETWORK_PORT_REFERENCE_PORT_NONE)) {
        printf("Error: Failed to add Network Port 1 (Vermilion).\n");
        return 1;
    }
    if (!BACnetStack_AddNetworkPortObject(
            g_deviceInstance, NETWORK_PORT_2_INSTANCE,
            NETWORK_PORT_NETWORK_TYPE_IPV4,
            NETWORK_PORT_PROTOCOL_LEVEL_BACNET_APPLICATION,
            NETWORK_NUMBER_PORT_2,
            NETWORK_NUMBER_QUALITY_CONFIGURED,
            NETWORK_PORT_REFERENCE_PORT_NONE)) {
        printf("Error: Failed to add Network Port 2 (Vermilion 2).\n");
        return 1;
    }

    // --- Enable the OPTIONAL properties we choose to expose ------------------
    if (!BACnetStack_SetPropertyEnabled(g_deviceInstance, OBJECT_TYPE_DEVICE,
                                        g_deviceInstance, PROPERTY_IDENTIFIER_DESCRIPTION, true)) {
        printf("Error: Failed to enable Description on the Device object.\n");
        return 1;
    }
    if (!BACnetStack_SetPropertyEnabled(g_deviceInstance, OBJECT_TYPE_MULTI_STATE_INPUT,
                                        MULTI_STATE_INPUT_INSTANCE, PROPERTY_IDENTIFIER_STATE_TEXT, true)) {
        printf("Error: Failed to enable State_Text on Multi-State Input 1 (Hot Pink).\n");
        return 1;
    }
    // Routing_Table (cl. 12.56.62) is INTENTIONALLY NOT enabled here.
    //
    // BACnetStack_AddNetworkPortObject's doc comment says it is served by the
    // stack "if you enable them" - but verified against the pinned stack
    // (abd4cee1) with a live client, enabling it and then reading it aborts
    // the request: BACnetBusinessLogic::UseCallbackGetList has no case for
    // Network Port/Routing_Table outside the forbidden A-side test-tool surface, so the
    // read always fails to encode. Enabling a property that is guaranteed to
    // abort on every read is worse than not claiming it at all - see TODO.md
    // and https://github.com/chipkin/cas-bacnet-stack/issues/2038.

    // --- Make the output objects commandable --------------------------------
    struct CommandableObject { uint16_t type; uint32_t instance; };
    const CommandableObject outputs[] = {
        { OBJECT_TYPE_ANALOG_OUTPUT,      ANALOG_OUTPUT_INSTANCE },
        { OBJECT_TYPE_BINARY_OUTPUT,      BINARY_OUTPUT_INSTANCE },
        { OBJECT_TYPE_MULTI_STATE_OUTPUT, MULTI_STATE_OUTPUT_INSTANCE },
    };
    for (size_t i = 0; i < sizeof(outputs) / sizeof(outputs[0]); ++i) {
        if (!BACnetStack_SetPropertyEnabled(g_deviceInstance, outputs[i].type, outputs[i].instance,
                                            PROPERTY_IDENTIFIER_PRIORITY_ARRAY, true) ||
            !BACnetStack_SetPropertyEnabled(g_deviceInstance, outputs[i].type, outputs[i].instance,
                                            PROPERTY_IDENTIFIER_RELINQUISH_DEFAULT, true) ||
            !BACnetStack_SetPropertyWritable(g_deviceInstance, outputs[i].type, outputs[i].instance,
                                             PROPERTY_IDENTIFIER_PRESENT_VALUE, true)) {
            printf("Error: Failed to make object type %u instance %u commandable.\n",
                   outputs[i].type, outputs[i].instance);
            return 1;
        }
    }

    // --- F-ROUTER: configure and enable physical routing ---------------------
    // AddRouterPort registers each DIRECTLY connected network (one call per
    // Network Port that participates - see its doc comment: "two or more
    // ports make the device a router").
    if (!BACnetStack_AddRouterPort(g_deviceInstance, ROUTER_PORT_ID_1,
                                   NETWORK_NUMBER_PORT_1, ROUTER_NETWORK_TYPE_IP)) {
        printf("Error: Failed to register router port 1 (network %u, Vermilion).\n",
               (unsigned)NETWORK_NUMBER_PORT_1);
        return 1;
    }
    if (!BACnetStack_AddRouterPort(g_deviceInstance, ROUTER_PORT_ID_2,
                                   NETWORK_NUMBER_PORT_2, ROUTER_NETWORK_TYPE_IP)) {
        printf("Error: Failed to register router port 2 (network %u, Vermilion 2).\n",
               (unsigned)NETWORK_NUMBER_PORT_2);
        return 1;
    }
    // AddRouterRoute: a static route to DEMO_REMOTE_NETWORK, one hop beyond
    // port 2, with no next-hop MAC configured (NULL/0 - "the relay falls back
    // to the egress link broadcast" per the doc comment). DEMONSTRATION ONLY:
    // see the DEMO_REMOTE_NETWORK comment above - nothing actually answers on
    // this network in this example series, and Routing_Table cannot be read
    // back at this pin (TODO.md), so this call demonstrates the AddRouterRoute
    // API accepting the configuration, not an end-to-end verified route.
    if (!BACnetStack_AddRouterRoute(g_deviceInstance, DEMO_REMOTE_NETWORK,
                                    ROUTER_PORT_ID_2, NULL, 0)) {
        printf("Error: Failed to configure the demonstration route to network %u.\n",
               (unsigned)DEMO_REMOTE_NETWORK);
        return 1;
    }
    // Routing is opt-in even with ports configured (SetRouterEnabled's doc
    // comment: "configuring ports alone does not start forwarding").
    if (!BACnetStack_SetRouterEnabled(g_deviceInstance, true)) {
        printf("Error: Failed to enable routing. (Built without STACK_OPTION_ROUTER_PHYSICAL?)\n");
        return 1;
    }

    // Who-Is is answered automatically on both ports (DM-DDB-B). Broadcast an
    // unsolicited I-Am on EACH network this device is on (DM-DDB-A/cl. 16.1 -
    // one I-Am per network the device is directly reachable from).
    CASExampleHelper::SendIAm(g_deviceInstance, NETWORK_PORT_1_INSTANCE);
    CASExampleHelper::SendIAm(g_deviceInstance, NETWORK_PORT_2_INSTANCE);

    // NM-RC-B: announce this router to both of its networks (I-Am-Router-To-
    // Network) and each network's own number (Network-Number-Is), and probe
    // each network for any OTHER router already present (Who-Is-Router-To-
    // Network, unrestricted query) - the polite router start-up sequence per
    // cl. 6.6.2. No other router is expected to answer in this example.
    AnnounceRouterToBothNetworks();
    {
        uint8_t cs1[6], cs2[6];
        BuildLocalBroadcastConnectionString(g_bacnetIpUdpPort1, cs1);
        BuildLocalBroadcastConnectionString(g_bacnetIpUdpPort2, cs2);
        BACnetStack_SendNetworkNumberIs(NETWORK_NUMBER_PORT_1, NETWORK_NUMBER_QUALITY_CONFIGURED,
                                        cs1, 6, NETWORK_PORT_1_INSTANCE, true, 0, NULL, 0);
        BACnetStack_SendNetworkNumberIs(NETWORK_NUMBER_PORT_2, NETWORK_NUMBER_QUALITY_CONFIGURED,
                                        cs2, 6, NETWORK_PORT_2_INSTANCE, true, 0, NULL, 0);
        BACnetStack_SendWhoIsRouterToNetwork(0, false, cs1, 6, NETWORK_PORT_1_INSTANCE, true, 0, NULL, 0);
        BACnetStack_SendWhoIsRouterToNetwork(0, false, cs2, 6, NETWORK_PORT_2_INSTANCE, true, 0, NULL, 0);
    }

    printf("FYI: Device %u (\"%s\") ready. Vendor ID %u. Routing network %u (Vermilion, UDP %u) "
           "<-> network %u (Vermilion 2, UDP %u). Press 'h' for help.\n",
           g_deviceInstance, DEVICE_NAME, VENDOR_IDENTIFIER,
           (unsigned)NETWORK_NUMBER_PORT_1, (unsigned)g_bacnetIpUdpPort1,
           (unsigned)NETWORK_NUMBER_PORT_2, (unsigned)g_bacnetIpUdpPort2);

    // --- Run the stack ------------------------------------------------------
    bool running = true;
    while (running) {
        BACnetStack_Tick();

        switch (CASExampleHelper::PollKey()) {
            case CASExampleHelper::KeyCommand::Help:
                CASExampleHelper::PrintHelp(APP_NAME, APP_VERSION);
                break;
            case CASExampleHelper::KeyCommand::Quit:
                running = false;
                break;
            case CASExampleHelper::KeyCommand::ArrowUp:
                g_analogInput1Value += 1.1f;
                printf("Analog Input 1 (Bronze) = %.1f C\n", g_analogInput1Value);
                break;
            case CASExampleHelper::KeyCommand::ArrowDown:
                g_analogInput1Value -= 1.1f;
                printf("Analog Input 1 (Bronze) = %.1f C\n", g_analogInput1Value);
                break;
            case CASExampleHelper::KeyCommand::RouterAnnounce:
                AnnounceRouterToBothNetworks();
                break;
            case CASExampleHelper::KeyCommand::None:
            default:
                break;
        }

#if defined(_WIN32)
        Sleep(1);
#else
        usleep(1000);
#endif
    }

    CASExampleHelper::RestoreInput();
    CASExampleHelper::ShutdownUDP();
    return 0;
}
